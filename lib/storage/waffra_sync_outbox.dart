import 'dart:convert';

import 'package:crypto/crypto.dart';
import 'package:drift/drift.dart';

import 'waffra_cloud_cipher.dart';
import 'waffra_encrypted_store.dart';

/// Local-only, disabled-by-default encryption-preserving replay preparation.
/// No Firebase SDK, network client or main.dart integration lives here.
///
/// Store this queue only inside the already encrypted SQLite database. This
/// prototype is NOT a production sync worker or a guarantee of atomic remote
/// conflict resolution. A future Firestore adapter must use transactions with
/// create-if-absent / compare-and-set semantics for every remote mutation.
class WaffraEncryptedCloudOutbox {
  const WaffraEncryptedCloudOutbox(this.database);

  final WaffraEncryptedStore database;

  static String documentId(String kind, String recordId) {
    if (!WaffraCloudSanitizer.allowedFields.containsKey(kind) ||
        recordId.trim().isEmpty || recordId.length > 128) {
      throw ArgumentError('Invalid cloud record identity.');
    }
    // Identity is based on BOTH kind and record ID: the same ID can exist in
    // an entry and a goal. Stable across app restarts and devices.
    return sha256.convert(utf8.encode(jsonEncode([kind, recordId]))).toString();
  }

  Future<void> _ensureSchema() async {
    await database.customStatement('''
CREATE TABLE IF NOT EXISTS cloud_encrypted_outbox (
  vault_id TEXT NOT NULL,
  mutation_id TEXT NOT NULL,
  document_id TEXT NOT NULL,
  kind TEXT NOT NULL,
  record_id TEXT NOT NULL,
  device_id TEXT NOT NULL,
  local_version INTEGER NOT NULL CHECK(local_version > 0),
  deleted INTEGER NOT NULL CHECK(deleted IN (0, 1)),
  encrypted_envelope_json TEXT NOT NULL,
  created_us INTEGER NOT NULL,
  PRIMARY KEY (vault_id, mutation_id)
)''');
    await database.customStatement('''
CREATE INDEX IF NOT EXISTS idx_cloud_outbox_pending
ON cloud_encrypted_outbox (vault_id, document_id, local_version)''');
  }

  /// The encrypted envelope must have been generated by WaffraCloudCipher.
  /// Caller commits this in the same encrypted database transaction as the
  /// local record change; integration with the live ledger is NOT done yet.
  Future<void> enqueue({
    required String vaultId,
    required WaffraEncryptedCloudRecord envelope,
    bool deleted = false,
  }) async {
    _checkIdentity(vaultId, envelope);
    final id = documentId(envelope.kind, envelope.recordId);
    final payload = jsonEncode(envelope.toFirestoreDocument(deleted: deleted));
    await _ensureSchema();
    await database.transaction(() async {
      final sameMutation = await database.customSelect('''
SELECT document_id, local_version, deleted, encrypted_envelope_json
FROM cloud_encrypted_outbox WHERE vault_id = ? AND mutation_id = ?
''', variables: [
        Variable.withString(vaultId),
        Variable.withString(envelope.mutationId),
      ]).getSingleOrNull();

      if (sameMutation != null) {
        if (sameMutation.read<String>('document_id') == id &&
            sameMutation.read<int>('local_version') == envelope.localVersion &&
            sameMutation.read<int>('deleted') == (deleted ? 1 : 0) &&
            sameMutation.read<String>('encrypted_envelope_json') == payload) {
          return; // Retried enqueue, same ciphertext and same nonce.
        }
        throw StateError('Mutation ID reused with different encrypted contents.');
      }

      final last = await database.customSelect('''
SELECT local_version FROM cloud_encrypted_outbox
WHERE vault_id = ? AND document_id = ?
ORDER BY local_version DESC LIMIT 1
''', variables: [
        Variable.withString(vaultId),
        Variable.withString(id),
      ]).getSingleOrNull();

      if (last != null &&
          envelope.localVersion <= last.read<int>('local_version')) {
        throw StateError('Cloud mutation version must increase per record.');
      }

      await database.customStatement('''
INSERT INTO cloud_encrypted_outbox
(vault_id, mutation_id, document_id, kind, record_id, device_id,
 local_version, deleted, encrypted_envelope_json, created_us)
VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
''', [
        vaultId, envelope.mutationId, id, envelope.kind, envelope.recordId,
        envelope.deviceId, envelope.localVersion, deleted ? 1 : 0, payload,
        DateTime.now().microsecondsSinceEpoch,
      ]);
    });
  }

  /// The earliest pending mutation for each record is returned. A second
  /// change to that same record must wait for the first server acknowledgement.
  /// Returns only the requested vault's records and never sends anything.
  Future<List<WaffraCloudQueueItem>> pending({
    required String vaultId,
    int limit = 100,
  }) async {
    if (vaultId.trim().isEmpty || limit < 1 || limit > 200) {
      throw ArgumentError('Invalid vault or queue batch limit.');
    }
    await _ensureSchema();
    final rows = await database.customSelect('''
SELECT vault_id, mutation_id, document_id, kind, record_id, device_id,
       local_version, deleted, encrypted_envelope_json
FROM cloud_encrypted_outbox WHERE vault_id = ?
ORDER BY created_us ASC, rowid ASC
''', variables: [Variable.withString(vaultId)]).get();

    final seenDocuments = <String>{};
    final selected = <WaffraCloudQueueItem>[];
    for (final row in rows) {
      final id = row.read<String>('document_id');
      if (!seenDocuments.add(id)) continue;
      final value = jsonDecode(row.read<String>('encrypted_envelope_json'))
          as Map<String, dynamic>;
      final envelope = WaffraEncryptedCloudRecord(
        kind: row.read<String>('kind'),
        recordId: row.read<String>('record_id'),
        deviceId: row.read<String>('device_id'),
        mutationId: row.read<String>('mutation_id'),
        localVersion: row.read<int>('local_version'),
        encryptionVersion: value['encryptionVersion'] as int,
        ciphertext: value['ciphertext'] as String,
        nonce: value['nonce'] as String,
        mac: value['mac'] as String,
      );
      _checkIdentity(vaultId, envelope);
      if (documentId(envelope.kind, envelope.recordId) != id ||
          envelope.encryptionVersion != 1 ||
          value['mutationId'] != envelope.mutationId ||
          value['deviceId'] != envelope.deviceId ||
          value['localVersion'] != envelope.localVersion ||
          value['kind'] != envelope.kind ||
          value['deleted'] != (row.read<int>('deleted') == 1)) {
        throw StateError('Encrypted outbox row failed its integrity checks.');
      }
      selected.add(WaffraCloudQueueItem(
        vaultId: vaultId, documentId: id, envelope: envelope,
        deleted: row.read<int>('deleted') == 1,
      ));
      if (selected.length >= limit) break;
    }
    return selected;
  }

  /// Mark a queue item complete ONLY AFTER the remote transaction reports the
  /// exact committed mutation. This does not perform that transaction.
  Future<void> acknowledge({
    required WaffraCloudQueueItem item,
    required WaffraRemoteRevision confirmedRemote,
  }) async {
    if (preflight(
      item: item, remote: confirmedRemote, consentGiven: true,
      identityVerified: true, recoveryReady: true,
      atomicRemoteTransportReady: true,
    ) != WaffraRemoteAction.alreadyApplied) {
      throw StateError('Cannot acknowledge a different remote revision.');
    }
    await _ensureSchema();
    await database.customStatement('''
DELETE FROM cloud_encrypted_outbox
WHERE vault_id = ? AND mutation_id = ? AND document_id = ?
  AND local_version = ?
''', [
      item.vaultId, item.envelope.mutationId, item.documentId,
      item.envelope.localVersion,
    ]);
  }

  /// This is ONLY a local decision against a freshly observed remote revision.
  /// It must be repeated atomically inside a future remote Firestore transaction
  /// to prevent TOCTOU overwrites. Null means the caller CONFIRMED absence.
  static WaffraRemoteAction preflight({
    required WaffraCloudQueueItem item,
    required WaffraRemoteRevision? remote,
    required bool consentGiven,
    required bool identityVerified,
    required bool recoveryReady,
    required bool atomicRemoteTransportReady,
  }) {
    if (!consentGiven || !identityVerified || !recoveryReady ||
        !atomicRemoteTransportReady) {
      return WaffraRemoteAction.blocked;
    }
    if (remote == null) return WaffraRemoteAction.createIfAbsent;
    if (remote.documentId == item.documentId &&
        remote.kind == item.envelope.kind &&
        remote.mutationId == item.envelope.mutationId &&
        remote.deviceId == item.envelope.deviceId &&
        remote.localVersion == item.envelope.localVersion &&
        remote.deleted == item.deleted) {
      return WaffraRemoteAction.alreadyApplied;
    }
    // No last-write-wins on financial records, even with a higher version.
    return WaffraRemoteAction.manualConflict;
  }

  static void _checkIdentity(
    String vaultId, WaffraEncryptedCloudRecord envelope,
  ) {
    if (vaultId.trim().isEmpty || vaultId.length > 128 ||
        envelope.encryptionVersion != 1 ||
        envelope.deviceId.trim().isEmpty || envelope.deviceId.length > 128 ||
        envelope.mutationId.trim().isEmpty ||
        envelope.mutationId.length > 128 ||
        envelope.localVersion <= 0 ||
        envelope.ciphertext.isEmpty ||
        envelope.nonce.isEmpty ||
        envelope.mac.isEmpty) {
      throw ArgumentError('Invalid encrypted outbox envelope.');
    }
    documentId(envelope.kind, envelope.recordId);
    try {
      if (base64Decode(envelope.nonce).length != 12 ||
          base64Decode(envelope.mac).length != 16) {
        throw const FormatException('Invalid cloud AEAD envelope sizes.');
      }
      base64Decode(envelope.ciphertext);
    } on FormatException {
      throw ArgumentError('Invalid cloud AEAD envelope encoding.');
    }
  }
}

enum WaffraRemoteAction {
  blocked,
  createIfAbsent,
  alreadyApplied,
  manualConflict,
}

class WaffraCloudQueueItem {
  const WaffraCloudQueueItem({
    required this.vaultId,
    required this.documentId,
    required this.envelope,
    required this.deleted,
  });

  final String vaultId;
  final String documentId;
  final WaffraEncryptedCloudRecord envelope;
  final bool deleted;
}

class WaffraRemoteRevision {
  const WaffraRemoteRevision({
    required this.documentId,
    required this.kind,
    required this.mutationId,
    required this.deviceId,
    required this.localVersion,
    required this.deleted,
  });

  final String documentId, kind, mutationId, deviceId;
  final int localVersion;
  final bool deleted;
}
